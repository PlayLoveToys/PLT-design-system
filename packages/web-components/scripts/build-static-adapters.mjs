const HEADER = (name, renderer) =>
  `{% comment %} GENERATED by packages/web-components/scripts/build-static-adapters.mjs from packages/design-system/renderers/liquid/${renderer}.liquid. Edit the renderer, then run \`npm run build:adapters\`. {% endcomment %}\n`;

function doc({ summary, params }) {
  const lines = params.map((entry) => {
    const [rawName, type, description] = entry.split("|");
    const optional = rawName.startsWith("[");
    const name = rawName.replace(/[[\]]/g, "");
    return `  @param {${type}} ${optional ? `[${name}]` : name} - ${description}`;
  });
  return `{% doc %}\n  Liquid adapter for the ${summary}\n  Self-contained: it renders no other snippet and needs no\n  JavaScript (the markup is styled by @playlovetoys/design-system).\n\n${lines.join("\n")}\n{% enddoc %}\n`;
}

export async function buildAdapter(name, spec) {
  const source = await readFile(`${renderers}${spec.renderer}.liquid`, "utf8");
  const body = source.replace(/^\s*\{%-?\s*comment\s*-?%\}[\s\S]*?\{%-?\s*endcomment\s*-?%\}\s*/, "").trimEnd();
  return `${doc(spec)}${HEADER(name, spec.renderer)}${body}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [name, spec] of Object.entries(STATIC_ADAPTERS)) {
    const file = `${adapters}${name}.liquid`;
    const next = await buildAdapter(name, spec);
    if (check) {
      const current = await readFile(file, "utf8").catch(() => "");
      if (current !== next) stale.push(`${name}.liquid`);
    } else {
      await writeFile(file, next);
    }
  }
  if (stale.length) {
    console.error(`Stale static Liquid adapters (run \`npm run build:adapters\`): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log(check ? "Static Liquid adapters are up to date." : `Wrote ${Object.keys(STATIC_ADAPTERS).length} static Liquid adapters.`);
}
