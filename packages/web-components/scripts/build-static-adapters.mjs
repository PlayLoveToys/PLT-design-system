#!/usr/bin/env node
/**
 * Generates the syncable Shopify Liquid snippets for the static design-system
 * renderers (packages/design-system/renderers/liquid/*.liquid), so a theme's
 * `sync:plt` (which copies adapters/liquid/plt-*.liquid) gets them without
 * hand-made forks. The renderer stays the single source of markup; this file
 * only adds the Shopify-facing `{% doc %}` contract and the plt- name.
 *
 *   node scripts/build-static-adapters.mjs          write adapters
 *   node scripts/build-static-adapters.mjs --check  fail when they are stale
 */
